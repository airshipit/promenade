# Apply the catalog (035-generate-catalog.sh): Calico and the kubeadm chart
# (day 2). Wait until the pod network is up and the anchor daemonsets have
# applied the chart configuration to all nodes.

set -ex

: "${WORK_DIR:="${HOME}/kubeadm-gate"}"
: "${CATALOG:="${WORK_DIR}/catalog"}"
: "${VALUES:="./tools/deployment/kubeadm/values.yaml"}"
: "${NAMESPACE:="kube-system"}"
: "${ANCHOR_TIMEOUT:="1800"}"

ANCHOR_PODS="release_group=kubeadm,application=kubernetes"

# admin.conf generated by kubeadm embeds the credentials
mkdir -p "${HOME}/.kube"
sudo install -m 0600 -o "$(id -u)" -g "$(id -g)" /etc/kubernetes/admin.conf "${HOME}/.kube/config"
kubectl get nodes -o wide

# kubeadm-config and kubelet-config ConfigMaps were created by kubeadm init,
# the catalog manages them from now on.
kubectl apply -k "${CATALOG}" --server-side --force-conflicts

kubectl -n kube-system rollout status daemonset/calico-node --timeout=600s
kubectl -n kube-system rollout status deployment/calico-kube-controllers --timeout=600s
kubectl wait --for=condition=Ready nodes --all --timeout=300s

# The anchor annotates nodes with checksums of the configuration it has
# applied: wait until they match the configuration of the catalog.
fs_file() {
  kubectl -n "${NAMESPACE}" get secret kubeadm-service-fs-allnodes \
    -o jsonpath="{.data.${1//./\\.}}" | base64 -d
}
EXPECTED_KUBEADM_SHA256=$(fs_file kubeadm_ClusterConfiguration | sha256sum | cut -d ' ' -f 1)
EXPECTED_KUBELET_SHA256=$(fs_file kubelet_config.yaml | sha256sum | cut -d ' ' -f 1)
EXPECTED_VERSION=$(fs_file kubeadm_ClusterConfiguration | sed -n 's/^ *kubernetesVersion: *//p')

anchor_applied() {
  local name
  for name in $(kubectl get nodes -l kubernetes-apiserver=enabled -o name); do
    [[ "$(kubectl get "${name}" -o jsonpath='{.metadata.annotations.last-applied-kubeadm-cfg-sha256}')" \
      == "${EXPECTED_KUBEADM_SHA256}" ]] || return 1
  done
  # an upgrade keeps the kubelet config checksum: wait for the kubelet
  # version too and for the end of the anchor drain
  for name in $(kubectl get nodes -o name); do
    [[ "$(kubectl get "${name}" -o jsonpath='{.metadata.annotations.last-applied-kubelet-cfg-sha256}|{.status.nodeInfo.kubeletVersion}|{.spec.unschedulable}')" \
      == "${EXPECTED_KUBELET_SHA256}|${EXPECTED_VERSION}|" ]] || return 1
  done
}

END=$(($(date +%s) + ANCHOR_TIMEOUT))
until anchor_applied; do
  if [[ "$(date +%s)" -gt "${END}" ]]; then
    echo "Timed out waiting for the anchor to apply the configuration" >&2
    kubectl -n "${NAMESPACE}" get pods -o wide
    kubectl -n "${NAMESPACE}" logs -l "${ANCHOR_PODS}" --tail=200 --prefix --max-log-requests=10 || true
    exit 1
  fi
  kubectl -n "${NAMESPACE}" get pods -l "${ANCHOR_PODS}" -o wide || true
  kubectl get nodes -o wide || true
  kubectl -n "${NAMESPACE}" logs -l "${ANCHOR_PODS}" --tail=20 --prefix --max-log-requests=10 || true
  sleep 30
done

kubectl -n "${NAMESPACE}" rollout status daemonset/kubeadm-service-masters-anchor --timeout=600s
kubectl -n "${NAMESPACE}" rollout status daemonset/kubeadm-service-workers-anchor --timeout=600s

# The cluster must stay healthy after the anchor took over
kubectl wait --for=condition=Ready nodes --all --timeout=300s
test -z "$(kubectl get nodes -o jsonpath='{.items[*].spec.unschedulable}')"
kubectl -n kube-system wait --for=condition=Ready pods --all --timeout=600s \
  --field-selector=status.phase!=Succeeded
kubectl get pods -A -o wide
