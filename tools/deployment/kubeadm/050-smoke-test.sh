# Check that the cluster is functional and its PKI was generated by kubeadm
# from the provided CA.

set -ex

: "${WORK_DIR:="${HOME}/kubeadm-gate"}"
: "${VALUES:="./tools/deployment/kubeadm/values.yaml"}"
: "${SMOKE_TEST_IMAGE:="quay.io/airshipit/network-multitool"}"
# ICMP payload of the pod to pod check, sent with fragmentation prohibited:
# 1372 + 28 bytes of headers fits the pod MTU of the gate
: "${SMOKE_TEST_PING_SIZE:="1372"}"

NODES=$(python3 -c '
import sys, yaml
for node in yaml.safe_load(open(sys.argv[1]))["nodes"]:
    print(node["name"], node["ip"], node["role"])' "${VALUES}")

kubectl get nodes -o wide
while read -r name ip role; do
  kubectl get node "${name}" -o jsonpath='{.status.addresses[?(@.type=="InternalIP")].address}' | grep -qx "${ip}"
  kubectl wait --for=condition=Ready node "${name}" --timeout=300s
  if [[ "${role}" == "control-plane" ]]; then
    kubectl -n kube-system wait --for=condition=Ready pod --timeout=300s \
      -l tier=control-plane --field-selector "spec.nodeName=${name}"
  fi
done <<< "${NODES}"
test "$(kubectl -n kube-system get pods -l component=etcd --no-headers | wc -l)" -eq 3

kubectl -n kube-system rollout status daemonset/kube-proxy --timeout=300s
kubectl -n kube-system rollout status deployment/coredns --timeout=300s
kubectl -n kube-system wait --for=condition=Ready pods --all --timeout=300s \
  --field-selector=status.phase!=Succeeded
kubectl get pods -A -o wide

# The PKI is issued by the provided CA (the only one in the values),
# certificates of the apiservers are served through the VIP as well
python3 -c 'import sys, yaml; print(yaml.safe_load(open(sys.argv[1]))["certs"]["ca"]["crt"], end="")' \
  "${WORK_DIR}/ca-values.yaml" > "${WORK_DIR}/ca.crt"
kubectl get --raw /livez --server https://127.0.0.1:6553 --certificate-authority "${WORK_DIR}/ca.crt"
while read -r _ ip role; do
  [[ "${role}" == "control-plane" ]] || continue
  kubectl get --raw /livez --server "https://${ip}:6443" --certificate-authority "${WORK_DIR}/ca.crt"
done <<< "${NODES}"

# Workloads: scheduling, pod network, cluster DNS, apiserver -> kubelet.
# The test pod runs on the last node (a worker), its peer on the first one:
# pod to pod traffic crosses the nodes. ping needs NET_RAW, CRI-O doesn't grant
# it by default.
run_pod() {
  local pod="$1" node="$2"
  kubectl delete pod "${pod}" --ignore-not-found --wait
  kubectl run "${pod}" --image="${SMOKE_TEST_IMAGE}" --restart=Never --override-type=strategic \
    --overrides="{\"apiVersion\": \"v1\", \"spec\": {\"nodeSelector\": {\"kubernetes.io/hostname\": \"${node}\"}, \"containers\": [{\"name\": \"${pod}\", \"securityContext\": {\"capabilities\": {\"add\": [\"NET_RAW\"]}}}]}}"
}
TEST_NODE=$(tail -n 1 <<< "${NODES}" | cut -d ' ' -f 1)
PEER_NODE=$(head -n 1 <<< "${NODES}" | cut -d ' ' -f 1)
run_pod smoke-test "${TEST_NODE}"
run_pod smoke-test-peer "${PEER_NODE}"
kubectl wait --for=condition=Ready pod smoke-test smoke-test-peer --timeout=300s
kubectl get pod smoke-test smoke-test-peer -o wide
PEER_IP=$(kubectl get pod smoke-test-peer -o jsonpath='{.status.podIP}')
kubectl exec smoke-test -- ping -c 3 -W 5 -M "do" -s "${SMOKE_TEST_PING_SIZE}" "${PEER_IP}"
kubectl exec smoke-test -- nslookup kubernetes.default.svc.cluster.local
kubectl exec smoke-test -- curl -skf https://kubernetes.default.svc.cluster.local/livez
kubectl logs smoke-test | tail -n 5
kubectl delete pod smoke-test smoke-test-peer --wait
