# The nodes held out of day 0 join the cluster over ssh: ssh-bootstrap.sh
# --join of the chart (charts/kubeadm/overrides/reference/ssh-orchestration-<ORCHESTRATION>.yaml)
# with the current PKI. After a rotation of the CAs the discovery of the
# joining nodes goes through the cluster-info ConfigMap the rebootstrap
# updated.
#
# NODES_ALL: all the nodes of the gate (generated by the zuul playbook), the
# ones missing in NODES join. As a provisioner would do: the nodes are added
# to the values first (full: their certificates), the chart in the cluster gets
# them (helm upgrade), then the nodes are bootstrapped.

set -exo pipefail

: "${WORK_DIR:="${HOME}/kubeadm-gate"}"
: "${KUBEADM_CHART:="./charts/kubeadm"}"
: "${NODES:="${WORK_DIR}/nodes.yaml"}"
: "${NODES_ALL:="${WORK_DIR}/nodes-all.yaml"}"
# the Kubernetes version till day 2
: "${DAY1_VALUES:="./tools/deployment/kubeadm/day1/version.yaml"}"
: "${CATALOG:="${WORK_DIR}/catalog"}"
: "${HELM:="helm"}"
# the reference orchestration: ca or full
: "${ORCHESTRATION:="ca"}"
# the values of the cluster: the reference orchestration
: "${VALUES:="${KUBEADM_CHART}/overrides/reference/ssh-orchestration-${ORCHESTRATION}.yaml"}"
# the key of the gate (the zuul playbook adds it to all the nodes)
: "${SSH_KEY:="${HOME}/.ssh/kubeadm-gate"}"

JOIN=$(python3 -c '
import sys, yaml
names = {node["name"] for node in yaml.safe_load(open(sys.argv[1]))["nodes"]}
for node in yaml.safe_load(open(sys.argv[2]))["nodes"]:
    if node["name"] not in names:
        print(node["name"])' "${NODES}" "${NODES_ALL}")
test -n "${JOIN}"

export HELM
export CHART_ARGS="kubeadm ${KUBEADM_CHART} -f ${VALUES} -f ${NODES_ALL} -f ${DAY1_VALUES}"
export PKI_VALUES="${WORK_DIR}/pki-values.yaml"
export SSH="ssh -o BatchMode=yes -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR -i ${SSH_KEY}"

# the values with the new nodes
cp "${NODES_ALL}" "${NODES}"
if [ "${ORCHESTRATION}" = full ]; then
  # shellcheck disable=SC2086 # CHART_ARGS is a list of arguments
  ${HELM} template ${CHART_ARGS} \
    --set manifests.secret_tools=true --set entrypoint.default=null \
    | sed -n 's/^ *gen-pki-full.sh: *\(.*\)/\1/p' | base64 -d \
    | bash -s -- --out-file "${PKI_VALUES}"
fi

# the chart in the cluster with them, as helm upgrade would do
./tools/deployment/kubeadm/035-generate-catalog.sh
kubectl apply -k "${CATALOG}/kubeadm" --server-side --force-conflicts

# shellcheck disable=SC2086 # CHART_ARGS is a list of arguments
${HELM} template ${CHART_ARGS} \
  --set manifests.secret_tools=true --set entrypoint.default=null \
  | sed -n 's/^ *ssh-bootstrap.sh: *\(.*\)/\1/p' | base64 -d > "${WORK_DIR}/ssh-bootstrap.sh"
test -s "${WORK_DIR}/ssh-bootstrap.sh"

# shellcheck disable=SC2086 # the names of the nodes
bash "${WORK_DIR}/ssh-bootstrap.sh" --join ${JOIN}

# Ready once the CNI agent is up on them
for node in ${JOIN}; do
  kubectl wait --for=condition=Ready "node/${node}" --timeout=300s
done
kubectl get nodes -o wide
