# Day 0 over ssh: the ssh-bootstrap.sh tool of the chart
# (charts/kubeadm/overrides/reference/ssh-orchestration-<ORCHESTRATION>.yaml) bootstraps all
# the nodes of the gate from this node: the PKI by gen-pki.sh of the chart
# (the CAs and the service account key, kubeadm generates the rest), the prep
# phases on all the nodes at once, kubeadm init on the first control plane
# node, kubeadm join of the rest at once.
#
# The tool is rendered with the orchestration and the nodes of the gate
# (generated by the zuul playbook from the job variables); it renders the
# bootstrap script of every node with them (CHART_ARGS) and the PKI.

set -exo pipefail

: "${WORK_DIR:="${HOME}/kubeadm-gate"}"
: "${KUBEADM_CHART:="./charts/kubeadm"}"
: "${NODES:="${WORK_DIR}/nodes.yaml"}"
# the Kubernetes version till day 2
: "${DAY1_VALUES:="./tools/deployment/kubeadm/day1/version.yaml"}"
: "${HELM:="helm"}"
# the reference orchestration: ca or full
: "${ORCHESTRATION:="ca"}"
# the values of the cluster: the reference orchestration
: "${VALUES:="${KUBEADM_CHART}/overrides/reference/ssh-orchestration-${ORCHESTRATION}.yaml"}"
# the key of the gate (the zuul playbook adds it to all the nodes)
: "${SSH_KEY:="${HOME}/.ssh/kubeadm-gate"}"

install -d -m 0700 "${WORK_DIR}"
export HELM
export CHART_ARGS="kubeadm ${KUBEADM_CHART} -f ${VALUES} -f ${NODES} -f ${DAY1_VALUES}"
# the catalog (035-generate-catalog.sh) is rendered with it too
export PKI_VALUES="${WORK_DIR}/pki-values.yaml"
# the nodes are new to this node
export SSH="ssh -o BatchMode=yes -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR -i ${SSH_KEY}"

# only the tools (entrypoint.default is off): the values need the PKI which
# doesn't exist yet
# shellcheck disable=SC2086 # CHART_ARGS is a list of arguments
${HELM} template ${CHART_ARGS} \
  --set manifests.secret_tools=true --set entrypoint.default=null \
  | sed -n 's/^ *ssh-bootstrap.sh: *\(.*\)/\1/p' | base64 -d > "${WORK_DIR}/ssh-bootstrap.sh"
test -s "${WORK_DIR}/ssh-bootstrap.sh"

bash "${WORK_DIR}/ssh-bootstrap.sh"
